#!/usr/bin/env python3
"""Embed web/index.html into firmware/mraf/webui.h.

The same HTML file is served directly by the native simulator, so the
firmware and simulator always present the same dashboard.
"""
from pathlib import Path
import argparse
import sys

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SRC = ROOT / "web" / "index.html"
ARDUINO_DST = ROOT / "firmware" / "mraf" / "webui.h"
ZEPHYR_DST = ROOT / "firmware" / "zephyr" / "build" / "webui.h"

MARKER = ')MRAF"'
DELIM = "MRAF"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--zephyr", action="store_true",
                    help="emit a plain C++ string header for the Zephyr build")
    ap.add_argument("--src", type=Path, default=DEFAULT_SRC)
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()

    src = args.src
    dst = args.out or (ZEPHYR_DST if args.zephyr else ARDUINO_DST)
    if not src.exists():
        print(f"missing {src}", file=sys.stderr)
        return 1
    html = src.read_text(encoding="utf-8")
    if MARKER in html:
        print("web/index.html contains the raw-string marker; refusing", file=sys.stderr)
        return 1
    if args.zephyr:
        out = (
            "// Auto-generated by tools/gen_webui.py. Do not edit by hand.\n"
            "// Source: web/index.html\n"
            "#pragma once\n"
            "static const char INDEX_HTML[] = R\"" + DELIM + "(\n"
            + html
            + "\n)" + DELIM + "\";\n"
        )
    else:
        out = (
            "// Auto-generated by tools/gen_webui.py. Do not edit by hand.\n"
            "// Source: web/index.html\n"
            "#pragma once\n"
            "#include <Arduino.h>\n"
            "static const char INDEX_HTML[] PROGMEM = R\"" + DELIM + "(\n"
            + html
            + "\n)" + DELIM + "\";\n"
        )
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(out, encoding="utf-8")
    try:
        shown = dst.relative_to(ROOT)
    except ValueError:
        shown = dst
    print(f"wrote {shown} ({len(out)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
